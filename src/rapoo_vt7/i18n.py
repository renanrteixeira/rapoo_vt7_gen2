def tr(key, lang=None, **kwargs):
    """Returns a localized string for `key` in `lang` (or the language stored
    in the config file when `lang` is None). Applies .format(**kwargs) when
    placeholders are present."""
    if lang is None:
        from .config import load_language  # local import avoids a circular import

        lang = load_language()
    entry = LANGS.get(lang, LANGS["pt_BR"])
    text = entry[key]
    return text.format(**kwargs) if kwargs else text
